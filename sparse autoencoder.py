def make_peak_fn(sae):
    def peak(text, latent):
        enc = tok(text, return_tensors="pt").to(device)
        with torch.no_grad():
            h = lm(**enc, output_hidden_states=True).hidden_states[SITE_LAYER + 1][0].float().cpu().numpy()
