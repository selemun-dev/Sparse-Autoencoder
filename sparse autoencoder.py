def evaluate_thresholds(sae, X, thresholds=(1e-6, 1e-2, 1e-1)):
    f = sae.encode(X); out = {}
    for t in thresholds:
        on = f > t
        out[t] = (round(float(on.sum(1).mean()), 1), round(float(100 * (on.mean(0) == 0).mean()), 1))
    return out

